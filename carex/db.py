"""Database layer: SQLite (local, tests) and PostgreSQL/Neon (online) behind one small interface.

SQL is written once with `?` placeholders and portable syntax. Timestamps are ISO-8601 UTC text, flags are 0/1.
Writers are serialised per provider: Postgres uses an advisory lock, SQLite serialises all writers (BEGIN IMMEDIATE).
"""
from __future__ import annotations

import re
import sqlite3
import threading
from contextlib import contextmanager
from typing import Any, Iterator

from .schema import MIGRATIONS

# SQLite's message names columns, not indexes; map each named unique index to its column signature.
_SQLITE_UNIQUE = {
    "appointments_idem": "appointments.tenant_id, appointments.idempotency_key",
    "appointments_slot": "appointments.provider_id, appointments.starts_at",
    "appointments_resource_slot": "appointments.resource_id, appointments.starts_at",
    "outbox_dedupe": "outbox.tenant_id, outbox.dedupe_key",
    "patients_one_self": "patients.user_id",
}


class Conn:
    """A connection scope: either the shared handle (autocommit statements) or an open transaction."""

    def __init__(self, kind: str, cur_factory, in_tx: bool = False):
        self.kind = kind
        self._cur = cur_factory
        self.in_tx = in_tx

    def _sql(self, sql: str) -> str:
        return sql.replace("?", "%s") if self.kind == "pg" else sql

    def all(self, sql: str, *params: Any) -> list[dict]:
        with self._cur() as cur:
            cur.execute(self._sql(sql), params)
            if cur.description is None:
                return []
            cols = [c[0] for c in cur.description]
            return [dict(zip(cols, r)) for r in cur.fetchall()]

    def get(self, sql: str, *params: Any) -> dict | None:
        rows = self.all(sql, *params)
        return rows[0] if rows else None

    def run(self, sql: str, *params: Any) -> int:
        with self._cur() as cur:
            cur.execute(self._sql(sql), params)
            return cur.rowcount

    @property
    def for_update(self) -> str:
        return " FOR UPDATE" if self.kind == "pg" else ""

    def lock(self, key: str) -> None:
        """Serialise writers for one key (a provider). SQLite already serialises every writer."""
        if self.kind == "pg":
            self.get("SELECT pg_advisory_xact_lock(hashtext(?)) AS l", key)


class Db(Conn):
    def __init__(self, kind: str, opener, closer, tx_factory):
        self._open, self._close, self._tx = opener, closer, tx_factory
        super().__init__(kind, opener)

    @contextmanager
    def tx(self) -> Iterator[Conn]:
        with self._tx() as c:
            yield c

    def close(self) -> None:
        self._close()

    def is_unique(self, e: Exception, index: str | None = None) -> bool:
        return is_unique(self.kind, e, index)


def is_unique(kind: str, e: Exception, index: str | None = None) -> bool:
    if kind == "sqlite":
        if not isinstance(e, sqlite3.IntegrityError) or "UNIQUE" not in str(e):
            return False
        return index is None or _SQLITE_UNIQUE.get(index, "\0") in str(e)
    try:
        import psycopg
    except ImportError:  # pragma: no cover
        return False
    if not isinstance(e, psycopg.errors.UniqueViolation):
        return False
    return index is None or getattr(e.diag, "constraint_name", None) == index


def _translate(stmt: str, kind: str) -> str:
    pk = "INTEGER PRIMARY KEY AUTOINCREMENT" if kind == "sqlite" else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    return stmt.replace("{ID}", pk)


def open_db(url: str | None = None, path: str | None = None) -> Db:
    """`url` = a postgresql:// connection string (Neon). Otherwise SQLite at `path` (default: in memory)."""
    if url and url.startswith(("postgres://", "postgresql://")):
        db = _open_pg(url)
    else:
        db = _open_sqlite(path or ":memory:")
    migrate(db)
    return db


def _open_sqlite(path: str) -> Db:
    con = sqlite3.connect(path, check_same_thread=False, isolation_level=None)   # autocommit; transactions are explicit
    con.execute("PRAGMA foreign_keys = ON")
    if path != ":memory:":
        con.execute("PRAGMA journal_mode = WAL")
    lock = threading.RLock()
    state = {"depth": 0}

    @contextmanager
    def cursor():
        with lock:
            cur = con.cursor()
            try:
                yield cur
            finally:
                cur.close()

    @contextmanager
    def tx():
        with lock:
            if state["depth"]:
                raise RuntimeError("nested transactions are not supported")
            con.execute("BEGIN IMMEDIATE")
            state["depth"] = 1
            try:
                yield Conn("sqlite", cursor, True)
                con.execute("COMMIT")
            except BaseException:
                try:
                    con.execute("ROLLBACK")
                except sqlite3.Error:
                    pass
                raise
            finally:
                state["depth"] = 0

    return Db("sqlite", cursor, con.close, tx)


def _open_pg(url: str) -> Db:
    from psycopg_pool import ConnectionPool

    # prepare_threshold=None keeps this safe behind Neon's pooled (PgBouncer) endpoint.
    pool = ConnectionPool(url, min_size=0, max_size=5, kwargs={"autocommit": True, "prepare_threshold": None}, open=True, timeout=10)

    @contextmanager
    def cursor():
        with pool.connection() as c:
            with c.cursor() as cur:
                yield cur

    @contextmanager
    def tx():
        with pool.connection() as c:
            c.autocommit = False
            try:
                def cur_factory():
                    return c.cursor()
                yield Conn("pg", cur_factory, True)
                c.commit()
            except BaseException:
                try:
                    c.rollback()
                except Exception:
                    pass
                raise
            finally:
                c.autocommit = True

    return Db("pg", cursor, pool.close, tx)


def migrate(db: Db) -> None:
    db.run("CREATE TABLE IF NOT EXISTS carex_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)")
    done = int((db.get("SELECT COALESCE(MAX(version), 0) AS v FROM carex_migrations") or {"v": 0})["v"])
    if done == 0 and db.kind == "pg" and db.get("SELECT 1 AS x FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'tenants'"):
        raise RuntimeError("This database already holds tables from a different CareX version. Point DATABASE_URL at an empty database (for example a new Neon branch).")
    for v in range(done, len(MIGRATIONS)):
        with db.tx() as tx:
            if tx.kind == "pg":
                tx.get("SELECT pg_advisory_xact_lock(727001) AS l")       # two instances starting together must not both migrate
            again = int(tx.get("SELECT COALESCE(MAX(version), 0) AS v FROM carex_migrations")["v"])
            if again > v:
                continue
            for stmt in MIGRATIONS[v]:
                tx.run(_translate(stmt, tx.kind))
            from .util import iso, now
            tx.run("INSERT INTO carex_migrations (version, applied_at) VALUES (?, ?)", v + 1, iso(now()))


