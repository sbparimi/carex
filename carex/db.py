"""Neon database layer. Neon exposes PostgreSQL's wire protocol and is accessed through psycopg.

CareX requires DATABASE_URL pointing to a Neon project. There is no SQLite or local-file fallback.
SQL uses ? placeholders translated to PostgreSQL parameters. Timestamps are ISO-8601 UTC text; flags are 0/1.
Writers are serialised per provider with transaction-scoped advisory locks.
"""
from __future__ import annotations

from contextlib import contextmanager
from typing import Any, Iterator

from .schema import MIGRATIONS

class Conn:
    """A connection scope: either the shared handle (autocommit statements) or an open transaction."""

    def __init__(self, kind: str, cur_factory, in_tx: bool = False):
        self.kind = kind
        self._cur = cur_factory
        self.in_tx = in_tx

    def _sql(self, sql: str) -> str:
        return sql.replace("?", "%s")

    def all(self, sql: str, *params: Any) -> list[dict]:
        with self._cur() as cur:
            cur.execute(self._sql(sql), params)
            if cur.description is None:
                return []
            cols = [c[0] for c in cur.description]
            return [dict(zip(cols, r)) for r in cur.fetchall()]

    def get(self, sql: str, *params: Any) -> dict | None:
        rows = self.all(sql, *params)
        return rows[0] if rows else None

    def many(self, sql: str, rows: list[tuple]) -> None:
        """Run one statement for many parameter rows (batched on Postgres, so large imports need few round trips)."""
        if not rows:
            return
        with self._cur() as cur:
            cur.executemany(self._sql(sql), rows)

    def run(self, sql: str, *params: Any) -> int:
        with self._cur() as cur:
            cur.execute(self._sql(sql), params)
            return cur.rowcount

    @property
    def for_update(self) -> str:
        return " FOR UPDATE"

    def lock(self, key: str) -> None:
        """Serialise concurrent writers for one provider across serverless instances."""
        self.get("SELECT pg_advisory_xact_lock(hashtext(?)) AS l", key)


class Db(Conn):
    def __init__(self, kind: str, opener, closer, tx_factory):
        self._open, self._close, self._tx = opener, closer, tx_factory
        super().__init__(kind, opener)

    @contextmanager
    def tx(self) -> Iterator[Conn]:
        with self._tx() as c:
            yield c

    def close(self) -> None:
        self._close()

    def is_unique(self, e: Exception, index: str | None = None) -> bool:
        return is_unique(self.kind, e, index)


def is_unique(kind: str, e: Exception, index: str | None = None) -> bool:
    try:
        import psycopg
    except ImportError:  # pragma: no cover
        return False
    if not isinstance(e, psycopg.errors.UniqueViolation):
        return False
    return index is None or getattr(e.diag, "constraint_name", None) == index


def _translate(stmt: str) -> str:
    return stmt.replace("{ID}", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")


def open_db(url: str | None = None) -> Db:
    """Open the configured Neon database. A Neon PostgreSQL connection URL is mandatory."""
    if not isinstance(url, str) or not url.startswith(("postgres://", "postgresql://")):
        raise RuntimeError("DATABASE_URL must be a Neon connection string. SQLite and local-file databases are not supported.")
    db = _open_pg(url)
    migrate(db)
    return db


def _open_pg(url: str) -> Db:
    from psycopg_pool import ConnectionPool

    # prepare_threshold=None keeps this safe behind Neon's pooled (PgBouncer) endpoint.
    pool = ConnectionPool(url, min_size=0, max_size=5, kwargs={"autocommit": True, "prepare_threshold": None}, open=True, timeout=10)

    @contextmanager
    def cursor():
        with pool.connection() as c:
            with c.cursor() as cur:
                yield cur

    @contextmanager
    def tx():
        with pool.connection() as c:
            c.autocommit = False
            try:
                def cur_factory():
                    return c.cursor()
                yield Conn("pg", cur_factory, True)
                c.commit()
            except BaseException:
                try:
                    c.rollback()
                except Exception:
                    pass
                raise
            finally:
                c.autocommit = True

    return Db("pg", cursor, pool.close, tx)


def migrate(db: Db) -> None:
    db.run("CREATE TABLE IF NOT EXISTS carex_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)")
    done = int((db.get("SELECT COALESCE(MAX(version), 0) AS v FROM carex_migrations") or {"v": 0})["v"])
    if done == 0 and db.get("SELECT 1 AS x FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'tenants'"):
        raise RuntimeError("This database already holds tables from a different CareX version. Point DATABASE_URL at an empty database (for example a new Neon branch).")
    for v in range(done, len(MIGRATIONS)):
        with db.tx() as tx:
            tx.get("SELECT pg_advisory_xact_lock(727001) AS l")       # two instances starting together must not both migrate
            again = int(tx.get("SELECT COALESCE(MAX(version), 0) AS v FROM carex_migrations")["v"])
            if again > v:
                continue
            for stmt in MIGRATIONS[v]:
                tx.run(_translate(stmt))
            from .util import iso, now
            tx.run("INSERT INTO carex_migrations (version, applied_at) VALUES (?, ?)", v + 1, iso(now()))

